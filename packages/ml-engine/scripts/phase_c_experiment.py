"""
Phase C experiment for the thesis: model comparison, generalisation to unseen
bot types, SHAP explanations, and raw-trajectory sequence models.

Usage (from packages/ml-engine; needs the [explain] and [deep] extras):
    python scripts/phase_c_experiment.py --out ../../docs/thesis/results/phase_c
    python scripts/phase_c_experiment.py --out /tmp/quick --quick      # small smoke run

Everything runs on synthetic data: it validates the methods and the pipeline;
it is not evidence about real users or real bots.
"""
import argparse
import json
import os
import sys
import time

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..'))

from aegis_ml.evaluation import compare, plots  # noqa: E402
from aegis_ml.evaluation.explain import try_explainer  # noqa: E402
from aegis_ml.models.classifier import BotClassifier  # noqa: E402


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', required=True)
    ap.add_argument('--seed', type=int, default=42)
    ap.add_argument('--quick', action='store_true', help='small sizes for a smoke test')
    ap.add_argument('--no-deep', action='store_true', help='skip the PyTorch sequence models')
    args = ap.parse_args()
    os.makedirs(args.out, exist_ok=True)
    q = args.quick
    started = time.time()
    report, results = [], {'config': vars(args)}

    # --- C1: feature models on identical CV folds --------------------------------
    n_h, n_b = (600, 120) if q else (2500, 500)
    X, y, types = compare.labelled_dataset(n_h, n_b, args.seed)
    cmp = compare.compare_models(X, y, types, folds=5, n_boot=200 if q else 1000, seed=args.seed)
    oof = cmp.pop('oof')
    results['comparison'] = cmp
    report += ['# Phase C results (synthetic data)', '',
               f'Generated by `scripts/phase_c_experiment.py` (seed {args.seed}).', '',
               f'## C1. Model comparison: 5-fold CV, {len(y)} sessions ({int(y.sum())} bots, 5 bot types)', '',
               *compare.summary_table(cmp), '',
               'Paired bootstrap differences, stacked ensemble minus each model (95% CI):', '',
               '| Model | ΔAUC-ROC | ΔRecall @ 2% FPR |', '|---|---|---|']
    for name, d in cmp['paired_vs_stacked_ensemble'].items():
        a, r = d['auc_roc'], d['recall_at_2pct_fpr']
        report.append(f"| {name} | {a['diff']:+.4f} ({a['ci_low']:+.4f}, {a['ci_high']:+.4f}) | "
                      f"{r['diff']:+.4f} ({r['ci_low']:+.4f}, {r['ci_high']:+.4f}) |")
    report += ['', 'Recall per bot type at the 2%-FPR operating point:', '',
               '| Model | ' + ' | '.join(sorted(next(iter(cmp['models'].values()))['per_type_recall_at_2pct_fpr'])) + ' |',
               '|---' * 6 + '|']
    for name, e in cmp['models'].items():
        pt = e['per_type_recall_at_2pct_fpr']
        report.append(f'| {name} | ' + ' | '.join(f'{pt[k]:.3f}' for k in sorted(pt)) + ' |')
    plots.roc_pr_figure(y, oof, args.out, 'fig_c1_roc_pr', 'Feature-based models, 5-fold out-of-fold predictions',
                        n_boot=100 if q else 300, seed=args.seed)

    loto = compare.leave_one_type_out(X, y, types, seed=args.seed)
    results['leave_one_type_out'] = loto
    report += ['', '## C1b. Unseen bot types (leave one type out)', '',
               'Train on half the humans + four bot types; test on the other humans + the held-out type.', '',
               '| Held-out type | ' + ' | '.join(next(iter(loto.values()))) + ' |', '|---' * 5 + '|']
    for t, row in loto.items():
        report.append(f'| {t} | ' + ' | '.join(f"AUC {v['auc_roc']:.3f} / R@2% {v['recall_at_2pct_fpr']:.3f}"
                                              for v in row.values()) + ' |')
    plots.heatmap_figure({t: {m: v['recall_at_2pct_fpr'] for m, v in row.items()} for t, row in loto.items()},
                         args.out, 'fig_c1_unseen_bot_types', 'Recall on a bot type never seen in training',
                         'Cell = bot recall at 2% false-positive rate on held-out humans + the held-out bot type.')

    # --- C2: SHAP -----------------------------------------------------------------
    clf = BotClassifier()
    clf.train(X, y)
    explainer = try_explainer(clf)
    if explainer is not None:
        sample = X[np.random.RandomState(args.seed).choice(len(X), min(2000, len(X)), replace=False)]
        imp, groups = explainer.global_importance(sample), explainer.group_importance(sample)
        agree = explainer.component_agreement(sample)
        sv = explainer.shap_values(sample[:50])
        margin = clf.models['xgboost'].predict(clf.scaler.transform(sample[:50]), output_margin=True)
        t0 = time.perf_counter()
        for row in sample[:200]:
            explainer.explain(row)
        results['shap'] = {'top_features': dict(list(imp.items())[:15]), 'groups': groups, 'agreement_spearman': agree,
                           'additivity_max_error': float(np.abs(sv.sum(1) + explainer.expected_value - margin).max()),
                           'explain_ms_per_request': (time.perf_counter() - t0) / 200 * 1000}
        plots.importance_figure(imp, groups, args.out)
        report += ['', '## C2. SHAP (TreeSHAP on the XGBoost component)', '',
                   '| Feature | Mean abs SHAP |', '|---|---|',
                   *[f'| {k} | {v:.3f} |' for k, v in list(imp.items())[:10]], '',
                   '| Category | Mean abs SHAP sum |', '|---|---|',
                   *[f'| {k} | {v:.3f} |' for k, v in sorted(groups.items(), key=lambda kv: -kv[1])], '',
                   f"Additivity check (sum of SHAP + base value = model log-odds): max error "
                   f"{results['shap']['additivity_max_error']:.1e}. Explanation time "
                   f"{results['shap']['explain_ms_per_request']:.2f} ms per request.",
                   f"Rank agreement (Spearman) with the other base models' importances: "
                   + ', '.join(f'{k} {v:.2f}' for k, v in agree.items()) + '.']

    # --- C3: raw trajectories ------------------------------------------------------
    if not args.no_deep:
        from aegis_ml.evaluation import trajectory_experiment as te
        from aegis_ml.trajectories.generator import TRAJECTORY_BOT_TYPES, TrajectoryGenerator
        tr = te.run(n_human=400 if q else 2000, n_bot_per_type=80 if q else 400, seed=args.seed,
                    epochs=4 if q else 20)
        mixed_test = tr.pop('mixed_test')
        results['trajectories'] = tr
        gen = TrajectoryGenerator(args.seed + 1)
        examples = {'human': gen.human(4)}
        for k in TRAJECTORY_BOT_TYPES:
            examples[k] = gen.bot(k, 4, gen.human(4) if k == 'replay' else None)
        plots.trajectory_examples_figure(examples, args.out)
        plots.roc_pr_figure(np.array(mixed_test['y']), {k: np.array(v) for k, v in mixed_test['probs'].items()},
                            args.out, 'fig_c3_trajectory_roc_pr', 'Raw mouse trajectories, mixed 70/30 split',
                            n_boot=100 if q else 300, seed=args.seed)
        plots.heatmap_figure({t: {m: v['recall_at_2pct_fpr'] for m, v in row.items()}
                              for t, row in tr['leave_one_type_out'].items()},
                             args.out, 'fig_c3_trajectory_unseen_types', 'Trajectory models on an unseen bot type',
                             'Cell = bot recall at 2% false-positive rate (held-out humans + held-out type).')
        report += ['', f"## C3. Raw mouse trajectories ({tr['n_trajectories']} trajectories, sequence length {tr['seq_len']})", '',
                   '| Model | AUC-ROC | PR-AUC | Recall @ 2% FPR | p50 latency |', '|---|---|---|---|---|',
                   *[f"| {m} | {v['auc_roc']:.4f} | {v['pr_auc']:.4f} | {v['recall_at_2pct_fpr']:.3f} | "
                     f"{tr['latency_ms_p50'].get(m, float('nan')):.2f} ms |" for m, v in tr['mixed'].items()], '',
                   'Leave one bot type out (AUC / recall @ 2% FPR):', '',
                   '| Held-out type | ' + ' | '.join(next(iter(tr['leave_one_type_out'].values()))) + ' |', '|---' * 5 + '|']
        for t, row in tr['leave_one_type_out'].items():
            report.append(f'| {t} | ' + ' | '.join(f"{v['auc_roc']:.3f} / {v['recall_at_2pct_fpr']:.3f}"
                                                  for v in row.values()) + ' |')

    results['runtime_seconds'] = round(time.time() - started, 1)
    report += ['', f"Runtime: {results['runtime_seconds']} s."]
    with open(os.path.join(args.out, 'results.json'), 'w') as f:
        json.dump(results, f, indent=2, default=float)
    with open(os.path.join(args.out, 'report.md'), 'w') as f:
        f.write('\n'.join(report) + '\n')
    print('\n'.join(report))


if __name__ == '__main__':
    main()
